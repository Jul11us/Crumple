#!/usr/bin/env python3
"""Turns Lucide SVG icons (ISC licence) into path data for the Windows app's Ui/IconData.cs.
Usage: python3 scripts/windows-icons.py <folder of lucide .svg files>"""
import os
import re
import sys
from pathlib import Path

COUNTS = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'S': 4, 'Q': 4, 'T': 2, 'A': 7, 'Z': 0}
NUM = re.compile(r'[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')


def normalize(d):
    """Spells every command and number out with spaces (Avalonia can't read packed arc flags)."""
    out, i, cmd = [], 0, None
    first = True
    while True:
        while i < len(d) and d[i] in ' ,\n\t':
            i += 1
        if i >= len(d):
            break
        relative_start = False
        if d[i].isalpha():
            cmd = d[i]
            i += 1
            # A path's first move is absolute even when written as "m"; the pairs after it stay relative.
            if first and cmd == 'm':
                cmd, relative_start = 'M', True
            if cmd.upper() == 'Z':
                out.append(cmd)
                continue
        out.append(cmd)  # spelled out every time, so implicit repeats survive
        first = False
        args = []
        for k in range(COUNTS[cmd.upper()]):
            while i < len(d) and d[i] in ' ,\n\t':
                i += 1
            if cmd.upper() == 'A' and k in (3, 4):
                args.append(d[i])
                i += 1
                continue
            m = NUM.match(d, i)
            args.append(m.group())
            i = m.end()
        out.append(' '.join(args))
        cmd = 'l' if relative_start else {'M': 'L', 'm': 'l'}.get(cmd, cmd)
    return ' '.join(out)


def shapes(svg):
    attrs = lambda s: dict(re.findall(r'([\w-]+)="([^"]*)"', s))
    for tag, body in re.findall(r'<(path|rect|circle|line|polyline|polygon|ellipse)\b([^>]*)/?>', svg):
        a = attrs(body)
        f = lambda k, default=None: float(a.get(k, default))
        if tag == 'path':
            yield a['d']
        elif tag == 'line':
            yield f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
        elif tag in ('polyline', 'polygon'):
            n = re.findall(r'[-\d.]+', a['points'])
            yield 'M' + ' L'.join(f"{n[k]} {n[k + 1]}" for k in range(0, len(n), 2)) + ('Z' if tag == 'polygon' else '')
        elif tag in ('circle', 'ellipse'):
            cx, cy = f('cx'), f('cy')
            rx, ry = (f('r'), f('r')) if tag == 'circle' else (f('rx'), f('ry'))
            yield f"M{cx - rx} {cy}A{rx} {ry} 0 1 0 {cx + rx} {cy}A{rx} {ry} 0 1 0 {cx - rx} {cy}Z"
        elif tag == 'rect':
            x, y, w, h, r = f('x', 0), f('y', 0), f('width'), f('height'), f('rx', 0)
            if r == 0:
                yield f"M{x} {y}H{x + w}V{y + h}H{x}Z"
            else:
                yield (f"M{x + r} {y}H{x + w - r}A{r} {r} 0 0 1 {x + w} {y + r}V{y + h - r}A{r} {r} 0 0 1 {x + w - r} {y + h}"
                       f"H{x + r}A{r} {r} 0 0 1 {x} {y + h - r}V{y + r}A{r} {r} 0 0 1 {x + r} {y}Z")


lines = []
for path in sorted(Path(sys.argv[1]).glob('*.svg')):
    key = ''.join(w.capitalize() for w in path.stem.split('-'))
    lines.append(f'    public const string {key} = "{" ".join(normalize(s) for s in shapes(path.read_text()))}";')
out = Path(__file__).resolve().parent.parent / 'Windows/Crumple.Desktop/Ui/IconData.cs'
out.write_text('''namespace Crumple.Desktop.Ui;

/// Line icons from Lucide (ISC licence, see THIRD-PARTY-NOTICES), drawn on a 24-unit grid with a 2-unit stroke.
/// They stand in for the SF Symbols of the Mac version, which can't be used on Windows.
/// Generated by scripts/windows-icons.py.
internal static class IconData
{
''' + '\n'.join(lines) + '\n}\n')
print(f"Wrote {len(lines)} icons")
