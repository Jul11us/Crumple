#!/usr/bin/env python3
"""Build bundle resources from the Swift compiler's extracted localization keys."""

import argparse
import json
import plistlib
import re
import subprocess
from pathlib import Path

from en import EN, INFO_PLIST


PLACEHOLDER = re.compile(r"%(?:\d+\$)?[-+#0 ]*\d*(?:\.\d+)?(lld|llu|ld|lu|lf|f|d|u|@|%)")
PLURAL = re.compile(r"\{([^{}|]+)\|([^{}]+)\}")


def signature(value):
    return [match[1] for match in PLACEHOLDER.finditer(value) if match[1] != "%"]


def plural_entry(value):
    groups = list(PLURAL.finditer(value))
    if not groups:
        return None
    if len(groups) != 1:
        raise ValueError(f"Expected one plural group: {value}")
    group = groups[0]
    one, other = group.groups()
    if signature(one) != ["lld"] or signature(other) != ["lld"]:
        raise ValueError(f"Plural forms must each contain one %lld: {value}")

    # Explicit argument positions let a plural follow a string, e.g. an app's name.
    template = value[:group.start()] + "%lld" + value[group.end():]
    plural_offset = group.start()
    index = 0

    def positional(match):
        nonlocal index
        if match[1] == "%":
            return "%%"
        index += 1
        if match.start() == plural_offset:
            return f"%{index}$#@count@"
        return f"%{index}$" + match[0][1:]

    return {
        "NSStringLocalizedFormatKey": PLACEHOLDER.sub(positional, template),
        "count": {
            "NSStringFormatSpecTypeKey": "NSStringPluralRuleType",
            "NSStringFormatValueTypeKey": "lld",
            "one": one,
            "other": other,
        },
    }


def write_strings(path, entries):
    lines = ["/* Generated by Localization/generate.py. */", ""]
    for key, value in sorted(entries.items()):
        lines.append(f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def generate(extracted, output):
    keys = set()
    files = sorted([*extracted.glob("*.strings"), *extracted.glob("*.stringsdata")])
    if not files:
        raise ValueError(f"No compiler-extracted localization files in {extracted}")
    # Ignore leftovers from renamed/deleted source files in incremental builds.
    sources = {path.stem for path in Path("Sources/Crumple").rglob("*.swift")}
    for path in files:
        if path.stem not in sources:
            continue
        if path.suffix == ".stringsdata":
            data = json.loads(path.read_text())
            keys.update(entry["key"] for entry in data.get("tables", {}).get("Localizable", []))
            continue
        result = subprocess.run(["plutil", "-convert", "json", "-o", "-", str(path)],
                                capture_output=True, text=True, check=True)
        keys.update(json.loads(result.stdout))

    missing = sorted(key for key in keys if re.search(r"[\u3400-\u9fff]", key) and key not in EN)
    if missing:
        raise ValueError("Missing English translations:\n" + "\n".join(repr(key) for key in missing))

    strings, plurals = {}, {}
    for key in sorted(keys):
        value = EN.get(key, key)
        flat = PLURAL.sub(lambda match: match[1], value)
        if signature(key) != signature(flat):
            raise ValueError(f"Format arguments differ: {key!r} -> {value!r}")
        plural = plural_entry(value)
        if plural:
            plurals[key] = plural
        else:
            strings[key] = value

    with Path("Resources/Info.plist").open("rb") as file:
        info = plistlib.load(file)
    for language, entries, info_entries in [
        ("en", strings, INFO_PLIST),
        ("zh-Hans", {key: key for key in keys}, {key: info[key] for key in INFO_PLIST}),
    ]:
        directory = output / f"{language}.lproj"
        directory.mkdir(parents=True, exist_ok=True)
        write_strings(directory / "Localizable.strings", entries)
        write_strings(directory / "InfoPlist.strings", info_entries)
        if language == "en":
            with (directory / "Localizable.stringsdict").open("wb") as file:
                plistlib.dump(plurals, file, sort_keys=True)
    print(f"Localized {len(keys)} keys in English and Simplified Chinese ({len(plurals)} English plural rules)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("extracted", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        generate(args.extracted, args.output)
    except (ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"{error}\n")
